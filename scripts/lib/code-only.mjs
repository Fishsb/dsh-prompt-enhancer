// ══════════════════════════════════════════════════════════════════════════════
// 病历一（D-10）：旧实现「**先剥块注释、再剥行注释**」
//     s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1')
//   该顺序把**任何** `/*` 当作块注释起点 ⇒ **`//` 行注释里的 `/*`**（`update/*`、
//   `src/host/**`、`lib/*.cjs` 等极常见形态）被误当块注释**开头** ⇒ 从该处起、
//   直到后面某个 `*/` 为止的整段（**含真实代码**）被整体剥掉。
//   实测：`lib/sys.cjs` 一条注释曾吞 **453 字符**，含 `return new Function(…)` 真实代码行。
//
// 病历二（R-1 · 独立复核实测 · P3-2e 修）：D-10 改成了「**先逐行剥 `//` → 再剥跨行块注释**」，
//   它在病历一那条上是对的，但**引入了另一条更坏的形态** ——
//     对 `/* note // more */ const REAL = 1;`（**单行内闭合的块注释，其中含 `//`**）：
//       第一步逐行剥 `//` 时，会把 `// more */ const REAL = 1;` **整段剥掉**
//       （连同该块注释的**闭合符 `*/`**）⇒ 行内留下一个**未闭合的 `/*`**
//       ⇒ 第二步从该处**一路吞到文件中下一个 `*/`**（含中间真实代码）。
//   ⚠ **旧实现（先块后行）在该形态上不吞**（它先用同行 `*/` 闭合该块）
//     ⇒ D-10 的修法**在这一支上比修前更坏**。（复核实测；本批已独立复现，见报告 §①。）
//
// ══════════════════════════════════════════════════════════════════════════════
// 本批修法（**只改「怎么剥」，不改「判什么」**）：由「多趟顺序替换」改为
//   **单趟左→右扫描**。一次扫描同时识别行注释与块注释，**互不产生未闭合残留**：
//     · 遇 `//`（且其前非 `:`）⇒ 剥到行尾，**永不**产生跨行影响；
//     · 遇 `/*` ⇒ 找**其后最近**的 `*/` 一并剥除（真正跨行的块注释亦在此一并处置）；
//     · 两者都不是的字符 ⇒ 原样保留。
//   ⇒ 顺序问题**从根上消失**：不存在「第一步把闭合符剥掉、第二步再去找它」的中间态。
//
// ══════════════════════════════════════════════════════════════════════════════
// 行为的**逐形态如实声明**（每形给「**是否成立** + **最坏情形**」；**不写**未经逐形态
// 对照的「不比现状更坏」式断言 —— 那正是 R-1 暴露出问题的地方）：
//
//   (a)  `//` 行注释里出现块注释起点符号 ⇒ **成立**：该符号随行注释一起消失，
//        **不影响其后任何行**（本模块首要修的那条）。
//   (b)  真正的**跨行** `/* … */` ⇒ **成立**：仍被完整剥除（含跨多行者）。
//   (b2) 块注释**跨行**、且其 `//` 与闭合符在**同一行**（`/* a\n // */ code`）⇒ **成立**
//        （多趟替换在此支会吞掉 `code`；本单趟扫描不会）。
//   (d1) **单行内闭合的块注释**（**无论其中是否含 `//`**）⇒ **成立**：
//        其后的真实代码**不被吞**。（R-1 要修的那条。）
//   (c)  **字符串字面量**内含 `/*` / `*/` ⇒ **不成立（已知未覆盖）**。
//        最坏情形：`const a = "/*"; const b = "*/"; const REAL = 1;`
//        —— 块扫描**不看字符串上下文**，会把两个字符串之间的**真实代码一并剥掉**。
//        ⚠ 该缺陷**与 D-10 修前修后同源**（两个旧实现同样如此，本模块**未**加重也未消除）；
//        真要治需上词法分析（识别字符串/模板串/正则字面量），**超出本批范围**。
//   (d)  **正则字面量 / 模板串**内含 `//` 或 `/*` ⇒ **不成立（已知未覆盖）**，同上：
//        `const re = /a\\/\\/b/;` 或 `` `${'//'}` `` 一类形态会被误判为注释起点。
//        ⚠ 同上：与旧实现同源，未加重亦未消除。
//   (e)  **URL 守护**：`//` 前一个字符为 `:`（含其间夹空格/制表符）⇒ **不剥**。
//        该口径**自旧实现沿用**（`(^|[^:])`），**属"判什么"** ⇒ 本批**原样保留**，不得改动。
//   (f)  **标记行**（如 `// ==PURE-BEGIN==`）⇒ 与注释同语法，**会被剥除**；需要该文本的
//        调用方**必须**在剥注释前取用。该性质**自旧实现沿用**，本批未改。
//
// 一句话：本模块的保证 = **(a)/(b)/(b2)/(d1) 成立**；**(c)/(d) 明确不保证**，且其缺陷
//   与旧实现同源（既未消除，也未加重）。

/**
 * 单趟左→右扫描剥注释（行注释 + 块注释）。
 *
 * 「行注释起点」的判据**刻意保留旧口径**：`//` 之前、**跳过空格/制表符后**的那个字符
 * **不得是 `:`** ⇒ 使 `https://…` 这类 URL **不被误剥**。这属「判什么」，本批**一字未改**。
 *
 * @param {string} src 源码文本
 * @returns {string} 剥注释后的文本（换行与行结构尽量保持，便于调用方按行定位）
 */
function stripComments(src) {
  const s = String(src);
  const n = s.length;
  const out = [];
  let start = 0; // 当前「未输出前缀」的起点
  let i = 0;
  while (i < n) {
    const c = s[i];
    if (c === '/' && s[i + 1] === '/') {
      // —— 行注释候选：先做 URL 守护（跳过空格/制表符回看一个字符）——
      let j = i - 1;
      while (j >= 0 && (s[j] === ' ' || s[j] === '\t')) j--;
      const prev = j >= 0 ? s[j] : '';
      if (prev === ':') { i += 1; continue; } // `http: //` / `https://` ⇒ 不是注释
      // 剥到行尾（**不含换行符**，换行原样保留）
      out.push(s.slice(start, i).replace(/[ \t]+$/, ''));
      i += 2;
      while (i < n && s[i] !== '\n') i++;
      start = i;
      continue;
    }
    if (c === '/' && s[i + 1] === '*') {
      const close = s.indexOf('*/', i + 2);
      if (close === -1) {
        // 未闭合：**不**吞掉其后内容 ⇒ 该 `/*` 当普通文本保留（与"找不到闭合符即不剥"一致）
        i += 2;
        continue;
      }
      out.push(s.slice(start, i));
      i = close + 2;
      start = i;
      continue;
    }
    i += 1;
  }
  out.push(s.slice(start));
  return out.join('');
}

/**
 * 剥注释后的代码文本（**单趟扫描口径**）。
 * @param {string} src 源码文本
 * @returns {string} 剥注释后的文本
 */
export function codeOnly(src) {
  return stripComments(src);
}

export default codeOnly;
