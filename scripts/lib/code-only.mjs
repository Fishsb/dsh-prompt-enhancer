//
// 病历（D-10 · P3-2b 报告登记）：此前 `arch-claims.mjs` 与 `dead-code-gate.mjs` 各自内联同一行
//   朴素剥离器 —— 先剥**块注释**、再剥行注释：
//       s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1')
//   ⚠ 该顺序有一个**会吞真实代码**的失效：**任何** `/*` 都被当作块注释起点 ⇒
//     **`//` 行注释里出现的 `/*`**（极常见形态：`update/*`、`src/host/**`、`lib/*.cjs`、
//     `prompts/*.md`、以及本仓注释里引用的 `/* */` 字面量）会被误当成块注释**开头**，
//     于是从该处起、**直到后面某个 `*/` 为止的整段（含真实代码）被整体剥掉**。
//   实测（P3-2b §⑥ D-10）：`lib/sys.cjs` 一条 P3-2a 注释曾吞掉 **453 字符**，其中含
//     `return new Function(pureText + …)` 这一**真实代码行** ⇒ 判据（`A197-3` / `R5` / `R6`）
//     对该区段**失明**，属「**让失败不可观测**」类缺陷（与 P2-1 `lib/**` 死码盲区同族）。
//
// 修法（**只改「怎么剥」，不改「判什么」**）：**先把行注释剥干净，再剥跨行块注释**。
//   顺序一换，`//` 里的 `/*` 就随该行一起消失，**不可能**再开启一个块注释区间。
//
// 行为的**明确边界**（如实声明，不冒充完备）：
//   · (a) `//` 行注释内出现 `/*` ⇒ **不再影响其后任何行**（本模块要修的那一条）；
//   · (b) 真正跨行的 `/* … */` 块注释 ⇒ **仍被正确剥离**（靠 `lineComment` 对块的豁免）；
//   · (c) **字符串字面量**内含 `/*` / `*/` ⇒ **不保证优于现状**：
//         块注释扫描仍不看字符串上下文（`const s = '/*'` 会被当作块注释起点）——
//         这一点**与旧实现同源、未改**（旧实现同样如此）。本模块只**不比现状更坏**；
//         真要治 (c) 需上词法分析，**超出本批范围**（作业书 §0-bis 第 3 条 (c) 允许明写）。
//   · (d) 正则字面量 / 模板串内含 `//`、`/*` 的形态 ⇒ 按上面的边界同理，**未专门处理**。

/**
 * 行注释匹配（`//…` 到行尾）。
 * 两个刻意保留的既有口径（**不得**在本次修正中改动）：
 *   ① `(^|[^:])` —— **要求 `//` 前一个字符不是 `:`**，使 `https://…` 这类 URL **不被误剥**
 *      （旧实现即此；改动它属「改判什么」）；
 *   ② **不匹配 `// ==PURE-BEGIN==` 这类标记行**是**旧实现就没有的能力** —— 但本模块**保留标记**：
 *      `lib/sys.cjs` 已不再用 PURE 标记，而 `test/*` 与若干判据**依赖**这些标记文本仍在
 *      ⇒ 本模块只剥「注释」的**语法**，不改变标记文本是否留存（剥后标记仍会消失，
 *      与旧实现一致 —— 需要标记的调用方**必须**在剥注释前取用，见各调用方注释）。
 */
const LINE_COMMENT = /(^|[^:])[ \t]*\/\/[^\n]*/g;
const BLOCK_COMMENT = /\/\*[\s\S]*?\*\//g;

/** 单行文本：剥掉该行内的行注释（保留行首非冒号字符）。 */
function stripLineComment(line) {
  return String(line).replace(LINE_COMMENT, '$1');
}

/**
 * 剥注释后的代码文本（**新口径**：先剥行注释，再剥跨行块注释）。
 * @param {string} src 源码文本
 * @returns {string} 剥注释后的文本（行数与结构尽量保持，便于调用方按行定位）
 */
export function codeOnly(src) {
  return String(src).split('\n').map(stripLineComment).join('\n').replace(BLOCK_COMMENT, '');
}

export default codeOnly;
