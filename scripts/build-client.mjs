// Build lib/client.cjs from src/client/**: inlines the dynamic client
// body into the static __ModuleLoader__ bundle. Run: node scripts/build-client.mjs
//
// v3.2.1-t（架构调整·漂移检测）：--check 模式重建到内存，与磁盘产物（lib/client.cjs）
// 对比——漂移即报错退出 1。供 sync-runtime / release / pre-commit 使用。
// P1a（2026-09-19）：root plugin-client.js 为孤儿产物，已退役并从本脚本产出面移除。
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { bundleModules } from './lib/module-bundler.mjs';

const require = createRequire(import.meta.url);
const root = dirname(dirname(fileURLToPath(import.meta.url)));

function buildClient() {
  // 目标模式：client 入口是普通 CommonJS 模块，由 module-bundler 打成自包含表达式。
  // 不再维护字符串骨架、注入标记或逐块拼接；装配失败 fail-closed。
  const appRuntime = bundleModules({
    root,
    entry: 'src/client/app.cjs',
  });
  if (!appRuntime.modules.includes('src/client/app.cjs')) {
    throw new Error('[build-client] 装配图不完整：缺少入口模块');
  }
  for (const required of [
    'src/client/common/runtime.cjs',
    'src/shared/contracts/client-runtime.cjs',
    'src/client/domains/enhance/components.cjs',
  ]) {
    if (!appRuntime.modules.includes(required)) {
      throw new Error('[build-client] 装配图不完整：缺少 ' + required);
    }
  }

  const embedded = appRuntime.code;

  const template = `// GENERATED by scripts/build-client.mjs — do not edit by hand.
// Rebuild after changing src/client/**: node scripts/build-client.mjs
window.__ModuleLoader__.load({
  id: "dsh-voice-prompt-enhancer",
  factory: (require) => {
    var module = { exports: {} }; var exports = module.exports;
    'use strict';

    const React = require('react');

    // RPC bridge to the host half's harness.handle handlers
    // (registered on /dsh-voice-prompt-enhancer/rpc by lib/index.cjs).
    const host = {
      call(method, args) {
        return fetch('/dsh-voice-prompt-enhancer/rpc', {
          method: 'POST',
          headers: { 'content-type': 'application/json' },
          body: JSON.stringify({ method, args: args || {} }),
        }).then((response) => response.json());
      },
    };

    // styles facade: inject CSS into a dedicated <style> tag.
    const styles = {
      insert(css) {
        if (document.querySelector('style[data-plugin-css="dsh-voice-prompt-enhancer"]') !== null) return;
        const tag = document.createElement('style');
        tag.dataset.plugin = 'dsh-voice-prompt-enhancer';
        tag.dataset.pluginCss = 'dsh-voice-prompt-enhancer';
        tag.textContent = css;
        document.head.appendChild(tag);
      },
    };

    // 目标模式：入口普通模块直接返回插件对象；环境依赖显式传入。
    const __DSH_CLIENT_APP__ = ${embedded};
    const plugin = __DSH_CLIENT_APP__.createClientApp({
      React, host, styles, window: typeof window !== 'undefined' ? window : null,
      document: typeof document !== 'undefined' ? document : null,
      navigator: typeof navigator !== 'undefined' ? navigator : null,
      MutationObserver: typeof MutationObserver !== 'undefined' ? MutationObserver : null,
      storage: typeof localStorage !== 'undefined' ? localStorage : null,
      setTimeout: typeof setTimeout !== 'undefined' ? setTimeout : null,
      clearTimeout: typeof clearTimeout !== 'undefined' ? clearTimeout : null,
      setInterval: typeof setInterval !== 'undefined' ? setInterval : null,
      clearInterval: typeof clearInterval !== 'undefined' ? clearInterval : null,
      console: typeof console !== 'undefined' ? console : null,
    });

    module.exports = { ...plugin, inject: ['slots', 'locale', 'timer'] };
    return module.exports;
  },
});
`;

  return { template };
}

const { template } = buildClient();
const args = process.argv.slice(2);

if (args.includes('--check')) {
  // v3.2.1-t（漂移检测）：产物与源码重建结果不一致即报错退出 1。
  // P1a：唯一 client 产物 = lib/client.cjs（孤儿 plugin-client.js 已退役，不再检）。
  let clientOk = true;
  try { clientOk = readFileSync(join(root, 'lib', 'client.cjs'), 'utf8') === template; } catch { clientOk = false; }
  if (clientOk) {
    console.log('lib/client.cjs OK（源码 ↔ 产物一致）');
    process.exit(0);
  }
  console.error('[build-client --check] 漂移检测失败：client 产物与源码重建结果不一致！');
  console.error('  修复：node scripts/build-client.mjs（重建产物），或还原被手改的产物。');
  process.exit(1);
}

mkdirSync(join(root, 'lib'), { recursive: true });
writeFileSync(join(root, 'lib', 'client.cjs'), template, 'utf8');
// ⚠ 口径订正（③ · 2026-10-16 门禁缺口批，与 build-host.mjs 同源）：`template.length` 是字符串长度
//   （UTF-16 码元数），不是字节数；本产物亦含 CJK（实测 252904 字符 vs 319470 字节）。
console.log('lib/client.cjs written (' + template.length + ' chars / ' + Buffer.byteLength(template, 'utf8') + ' bytes)');
